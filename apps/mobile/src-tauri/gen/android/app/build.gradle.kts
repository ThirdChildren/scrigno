// Release signing (`docs/ROADMAP.md` M5): `keystore.properties` is gitignored (root
// `.gitignore`: `**/keystore.properties`, `**/*.jks`, `**/*.keystore`) and never committed — it
// holds the path to the owner's production signing key plus its passwords. See the repo README's
// "Android" section for the `keytool -genkeypair` command that creates it. When the file is
// absent (e.g. this sandbox, or a contributor's fresh checkout), the `release` build type below
// gets no `signingConfig` at all — the Android Gradle Plugin's documented behaviour for that is
// an **unsigned** release APK/AAB (only the built-in `debug` build type has an implicit default
// signing config), not a build failure, so `just apk` still succeeds; the artifact just isn't
// installable until someone signs it. That's the "fallback gracefully" this milestone asks for,
// verified against an actual build without a keystore present this milestone (see the M5 report).
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties()
val hasReleaseKeystore = keystorePropertiesFile.exists()
if (hasReleaseKeystore) {
    keystorePropertiesFile.inputStream().use { keystoreProperties.load(it) }
}

